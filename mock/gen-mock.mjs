/* ---------- 相关阅读：同分类、排除自身、两项不同；优先「同书不同角度 + 同分类另一篇」 ---------- */
function relatedFor(post) {
  const cands = posts.filter((p) => p.id !== post.id && p.category === post.category)
  const score = (p) => {
    const sameBook = postBook.get(p.id).name === postBook.get(post.id).name
    const tagHit = p.tags.filter((t) => post.tags.includes(t)).length
    return (sameBook ? 100 : 0) + tagHit * 12 + (p.author.id === post.author.id ? 4 : 0)
  }
  cands.sort((a, b) => score(b) - score(a) || a.id.localeCompare(b.id))
  const first = cands[0]
  if (!first) throw new Error(post.id + ' 没有同分类候选')
  const firstBook = postBook.get(first.id).name
  let second = cands.slice(1).find((p) => postBook.get(p.id).name !== firstBook)
  if (!second) second = cands[1]
  if (!second) throw new Error(post.id + ' 相关阅读不足两篇')
  const pack = (p) => ({ id: p.id, title: p.title, cover: p.cover, time: p.time })
  return [pack(first), pack(second)]
}

