/* ---------- 正文 DSL：普通行=段落，> =引文，- =列表，## =小标题 ---------- */
function renderBody(text) {
  const lines = text.trim().split('\n').map((s) => s.trim()).filter(Boolean)
  const out = []
  let list = []
  const flush = () => {
    if (list.length) {
      out.push('<ul>' + list.map((li) => `<li>${esc(li)}</li>`).join('') + '</ul>')
      list = []
    }
  }
  for (const line of lines) {
    if (line.startsWith('- ')) { list.push(line.slice(2)); continue }
    flush()
    if (line.startsWith('> ')) out.push(`<blockquote>${esc(line.slice(2))}</blockquote>`)
    else if (line.startsWith('## ')) out.push(`<h2>${esc(line.slice(3))}</h2>`)
    else out.push(`<p>${esc(line)}</p>`)
  }
  flush()
  return out.join('')
}

/* 把补写段落插在收束段之前，保留每篇原来的结尾 */
function withCoda(body, coda) {
  const lines = body.trim().split('\n')
  let i = lines.length - 1
  while (i >= 0 && /^(- |> |## )/.test(lines[i].trim())) i--
  if (i < 0) return body + '\n' + coda
  lines.splice(i, 0, coda)
  return lines.join('\n')
}

/* ---------- 标签：集合互不相同，且保留 8 个固定标签 ---------- */
const TAG_COMBOS = []
for (let mask = 1; mask < 256; mask++) {
  const combo = TAGS.filter((_, i) => mask & (1 << i))
  if (combo.length >= 2 && combo.length <= 4) TAG_COMBOS.push(combo)
}
const usedTagKeys = new Set()
function tagsFor(idx, category) {
  const pref = CATEGORY_TAGS[category]
  const must = idx < TAGS.length ? TAGS[idx] : null
  for (let k = 0; k < TAG_COMBOS.length; k++) {
    const combo = TAG_COMBOS[(idx * 37 + k) % TAG_COMBOS.length]
    if (!combo.some((t) => pref.includes(t))) continue
    if (must && !combo.includes(must)) continue
    const key = combo.slice().sort().join('|')
    if (usedTagKeys.has(key)) continue
    usedTagKeys.add(key)
    return [...pref.filter((t) => combo.includes(t)), ...combo.filter((t) => !pref.includes(t))]
  }
  throw new Error('无法为第 ' + idx + ' 篇找到不重复的标签组合')
}


/* 标题里补上书名，但不套同一个「读后感」句式：按标题类型轮换 6 种自然说法 */
function withBookName(book, title, idx) {
  if (title.includes('《' + book + '》') || title.includes(book)) return title
  if (title.startsWith('重读')) return `重读《${book}》：${title.slice(2)}`
  if (/[：:]/.test(title)) return `${title}——读《${book}》`
  const forms = [
    `《${book}》里，${title}`,
    `读《${book}》：${title}`,
    `${title}——读《${book}》`,
    `《${book}》笔记：${title}`,
    `关于《${book}》：${title}`,
    `《${book}》中的一个细节：${title}`,
  ]
  return forms[(idx * 7 + book.length) % forms.length]
}

